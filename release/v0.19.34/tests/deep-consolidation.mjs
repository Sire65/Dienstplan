import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

const here=path.dirname(fileURLToPath(import.meta.url));
const site=path.resolve(here,'../site');
const read=p=>fs.readFileSync(path.join(site,p),'utf8');
const app=read('src/ui/app.js'),css=read('src/ui/app.css'),html=read('index.html');
const storage=read('src/adapters/storage.js'),sync=read('src/adapters/sync.js');
const auth=read('src/core/auth.js'),planning=read('src/core/planning.js');
const staffing=read('src/core/staffing.js'),security=read('src/core/security-core.js');
const provider=read('src/adapters/supabase-provider.js'),push=read('src/adapters/push.js');
const sw=read('service-worker.js'),update=read('src/core/update-manager.js');
const manifest=JSON.parse(read('update-manifest.json'));
const checks=[];
const check=(group,name,ok)=>checks.push({group,name,ok:!!ok});

check('Release','Version konsistent',manifest.version==='0.19.34'&&update.includes("CURRENT_RELEASE='0.19.34'")&&html.includes('?v=0.19.34'));
check('Release','60 Laufzeitdateien im Manifest',manifest.files.length===60);
check('Release','Manifestpfade eindeutig',new Set(manifest.files.map(x=>x.path)).size===manifest.files.length);
check('Release','Alle Manifestdateien vorhanden',manifest.files.every(x=>fs.existsSync(path.join(site,x.path))));
check('Release','Dateigrößen stimmen',manifest.files.every(x=>fs.statSync(path.join(site,x.path)).size===x.bytes));
check('Release','SHA-256 stimmt',manifest.files.every(x=>crypto.createHash('sha256').update(fs.readFileSync(path.join(site,x.path))).digest('hex')===x.sha256));
check('Architektur','Core Adapter UI getrennt',['src/core/','src/adapters/','src/ui/'].every(p=>fs.existsSync(path.join(site,p))));
check('Architektur','Keine Module fehlen',[...html.matchAll(/<script src="([^"]+)/g)].every(m=>fs.existsSync(path.join(site,m[1].split('?')[0]))));
check('Architektur','Service Worker nutzt eigene Releasekennung',sw.includes('0.19.34'));
check('Architektur','Update prüft Manifest',update.includes('update-manifest.json'));
check('Sicherheit','AES-GCM aktiv',security.includes('AES-GCM'));
check('Sicherheit','PBKDF2 aktiv',security.includes('PBKDF2'));
check('Sicherheit','Private VAPID-Schlüssel nicht im Browser',!push.includes('VAPID_PRIVATE_KEY')&&!app.includes('VAPID_PRIVATE_KEY'));
check('Sicherheit','Berechtigung vor Planänderung',app.includes("K.auth?.has('roster.plan.edit')"));
check('Sicherheit','Supabase-Sitzung wird geprüft',provider.includes('getSession')||provider.includes('ensureSession'));
check('IndexedDB','Verschlüsselter Speicherpfad vorhanden',storage.includes('encrypt')&&storage.includes('decrypt'));
check('IndexedDB','Schreib-Lese-Löschtest vorhanden',storage.includes('async test')||storage.includes('test:'));
check('IndexedDB','Erfolgreiches Speichern setzt Status grün',app.includes("setIdbStatus(true,'Änderung verschlüsselt in IndexedDB gespeichert'"));
check('IndexedDB','Fehler trennt DB und Entschlüsselung',app.includes("const connectionFault=startupStage==='indexeddb-open'"));
check('Offline','Outbox wird lokal gesichert',sync.includes("'syncOutbox'"));
check('Offline','Wiederholungszeit vorhanden',sync.includes('nextAttemptAt'));
check('Offline','Speichern wartet auf Outbox',app.includes('await K.sync?.whenDurable?.()'));
check('Planung','Z aus Standbesetzung ausgeschlossen',planning.includes('const active=allActive.filter(s=>!K.isSpecialShift(s))'));
check('Planung','Z separat gezählt',planning.includes('specialActive'));
check('Planung','Überschneidungen werden geprüft',planning.includes('Überschneidung mit bestehendem Dienst'));
check('Planung','Personenwechsel prüft Zielregeln',staffing.includes('sameOwner=existing&&existing.personId===candidate.personId'));
check('Bedienung','Doppelklick Balken öffnet Details',app.includes("e.stopPropagation();openShiftEditor"));
check('Bedienung','Doppelklick Name öffnet Person',app.includes('openPersonalOverview(el.dataset.person)'));
check('Bedienung','Ziehschwelle verhindert Fehlbedienung',app.includes('Math.hypot(dx,dy)<6'));
check('Bedienung','Zielablage grün oder rot',app.includes("blocked?'drop-invalid':'drop-valid'")&&css.includes('.drop-target.drop-valid')&&css.includes('.drop-target.drop-invalid'));
check('Bedienung','Ablehnung erklärt den Grund',app.includes('Ablegen bei ${target} nicht möglich: ${error.text}'));
check('Bedienung','Schnellplanung speichert direkt',app.includes("reason:'Schnellplanung im Zeitraster'")&&app.includes('await persist()'));
check('Bedienung','Farblegende belegt keine neue Zeile',html.includes('id="colorLegendBtn"')&&css.includes('.color-legend-popover{position:fixed'));
check('Bedienung','Farblegende verschwindet bei Platzmangel',css.includes('@media(max-width:1450px){.color-legend-trigger{display:none}'));
check('Bedienung','Farblegende erklärt fünf Zustände',['Blau','Grau','Braun-Gold','Grün','Rot'].every(x=>app.includes(x)));
check('Barrierearm','Statusmeldungen sind live',html.includes('aria-live="polite"'));
check('Barrierearm','Legende hat Schließbeschriftung',app.includes('aria-label="Farblegende schließen"'));
check('Datenqualität','Persönliche Höchstzeit verständlich',staffing.includes('Persönliche Höchstzeit an diesem Tag: maximal'));
check('Datenqualität','Altüberschreitung blockiert Verschieben nicht',staffing.includes('dayHours>oldDayHours+1e-9'));
check('Push','Push erfordert Serverfunktion',push.includes('kc-dp-push'));

let passed=0;
for(const x of checks){console.log(`${x.ok?'PASS':'FAIL'} [${x.group}] ${x.name}`);if(x.ok)passed++;}
console.log(`TÜV/STUDIO/ARCHITEKTUR ${passed}/${checks.length}`);
if(passed!==checks.length)process.exitCode=1;
