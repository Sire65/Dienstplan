const fs=require('fs'),path=require('path');
const current=require('../release/current.json');
const root=path.join(__dirname,'..',current.releasePath,'pilot-mobile');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const html=read('index.html'),app=read('app-v4.js'),css=read('app-v4.css'),sw=read('sw.js'),test=read('test.html');
const android=JSON.parse(read('manifest-android.webmanifest')),ios=JSON.parse(read('manifest-ios.webmanifest'));
const must=(v,m)=>{if(!v)throw new Error(m)};
must(/app-v4\.js/.test(html)&&/app-v4\.css/.test(html),'mobile pilot v4 assets missing');
must(/kc_dp_mobile_entry_v1/.test(app),'entry persistence missing');
must(/\^kc-dp-i-/.test(app),'opaque entry validation missing');
must(/Nochmal versuchen/.test(html),'retry action missing');
must(/Abbrechen/.test(html),'abort action missing');
must(/Meldung senden/.test(html),'report action missing');
must(/PUSH ERLAUBEN/.test(html),'push action missing');
must(/INSTALLIEREN/.test(html),'Android install action missing');
must(/Zum Home-Bildschirm/.test(html),'iOS install guidance missing');
must(/report_error/.test(app),'error telemetry missing');
must(/serviceWorker\.register/.test(app),'service worker registration missing');
must(/accessMode/.test(app),'server access mode missing');
must(/mode==='member'/.test(app),'member access state missing');
must(/mode==='test'/.test(app),'test access state missing');
must(/kein Benutzerzugang freigeschaltet/.test(app),'no-access state missing');
must(/Köcheclub-Daten bleiben gesperrt/.test(app),'no-access privacy message missing');
must(/test\.html/.test(app),'isolated test route missing');
must(/echten Köcheclub-Daten/.test(test),'test isolation notice missing');
must(!/supabase\.co|KC_WERNE|kc_dp_memberships/i.test(test),'test sandbox must not connect to real backend');
must(/completion_received/.test(sw),'completion push receipt missing');
must(/test_received/.test(sw),'test push receipt missing');
must(/entry=/.test(sw),'service worker entry binding missing');
for(const src of [html,app,sw,test])must(!/[a-f0-9]{48}/i.test(src),'raw pilot token leaked into mobile assets');
must(android.display==='standalone'&&ios.display==='standalone','standalone manifest missing');
must(!Object.prototype.hasOwnProperty.call(ios,'start_url'),'iOS must preserve installing document URL');
must(Array.isArray(android.icons)&&android.icons.some(x=>x.sizes==='192x192')&&android.icons.some(x=>x.sizes==='512x512'),'Android install icons missing');
must(css.length>500,'mobile pilot styles missing');
console.log(`KC DP2 V${current.version} install/access separation gate: PASS`);
