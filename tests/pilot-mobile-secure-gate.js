const fs=require('fs'),path=require('path');
const current=require('../release/current.json');
const root=path.join(__dirname,'..',current.releasePath,'pilot-mobile');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const html=read('index.html'),sw=read('sw.js');
const android=JSON.parse(read('manifest-android.webmanifest')),ios=JSON.parse(read('manifest-ios.webmanifest'));
const must=(v,m)=>{if(!v)throw new Error(m)};
must(/kc_dp_mobile_entry_v1/.test(html),'entry persistence missing');
must(/\^kc-dp-i-/.test(html),'opaque entry validation missing');
must(/Nochmal versuchen/.test(html),'retry action missing');
must(/Abbrechen/.test(html),'abort action missing');
must(/Meldung senden/.test(html),'report action missing');
must(/PUSH ERLAUBEN/.test(html),'push action missing');
must(/INSTALLIEREN/.test(html),'Android install action missing');
must(/Zum Home-Bildschirm/.test(html),'iOS install guidance missing');
must(/report_error/.test(html),'error telemetry missing');
must(/serviceWorker\.register/.test(html),'service worker registration missing');
must(/entry=/.test(sw),'service worker entry binding missing');
must(!/[a-f0-9]{48}/i.test(html),'raw pilot token leaked into HTML');
must(!/[a-f0-9]{48}/i.test(sw),'raw pilot token leaked into service worker');
must(android.display==='standalone'&&ios.display==='standalone','standalone manifest missing');
must(!Object.prototype.hasOwnProperty.call(ios,'start_url'),'iOS must preserve installing document URL');
must(Array.isArray(android.icons)&&android.icons.some(x=>x.sizes==='192x192')&&android.icons.some(x=>x.sizes==='512x512'),'Android install icons missing');
console.log(`KC DP2 V${current.version} secure mobile pilot gate: PASS`);
