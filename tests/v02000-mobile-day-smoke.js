function ok(cond,msg){if(!cond){console.error('FAIL:',msg);process.exitCode=1}else console.log('OK:',msg)}
ok(device.includes('const isPhone=()=>innerWidth<=600'),'Device-UX begrenzt Handyfunktion auf <=600px');
