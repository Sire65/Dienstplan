'use strict';
const fs=require('fs'),path=require('path');
const current=require('../release/current.json');
const root=path.join(__dirname,'..',current.releasePath);
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const must=(v,m)=>{if(!v)throw new Error(m)};
const index=read('index.html');
const tableCore=read('src/core/table-core-adapter.js');
const adapter=read('src/adapters/installations.js');
const ui=read('src/ui/installation-center.js');
const css=read('src/ui/installation-center.css');
const pilot=read('pilot-mobile/app-v4.js');
const sw=read('pilot-mobile/sw.js');
const test=read('pilot-mobile/test.html');

must(/installation-center\.css\?v=0\.19\.51-install-1/.test(index),'installation center css not wired');
must(/table-core-adapter\.js\?v=0\.19\.51-install-1/.test(index),'Table Core adapter not wired');
must(/adapters\/installations\.js\?v=0\.19\.51-install-1/.test(index),'installation adapter not wired');
must(/installation-center\.js\?v=0\.19\.51-install-1/.test(index),'installation center not wired');
must(/selectable!==false/.test(tableCore),'Table Core non-selectable mode missing');
must(/filterPlaceholder/.test(tableCore)&&/countLabel/.test(tableCore),'Table Core generic labels missing');
must(/kc_dp_installation_admin_list/.test(adapter),'installation admin RPC missing');
must(!/service_role|SUPABASE_SERVICE_ROLE_KEY/i.test(adapter),'browser adapter must not contain service role access');
must(/K\.tableCore/.test(ui),'installation center must use Table Core');
for(const key of ['installed_at','device_type','platform','app_version','push_enabled_at','test_received_at','access_mode','completed_at'])must(ui.includes(key),`installation column missing: ${key}`);
must(/Installationshistorie/.test(ui)&&/Handy/.test(ui)&&/Tablet/.test(ui)&&/PC/.test(ui),'installation UX labels missing');
must(/Nochmal versuchen/.test(ui),'installation retry action missing');
must(css.length>2000,'installation center styling unexpectedly small');
must(/accessMode/.test(pilot)&&/kein Benutzerzugang freigeschaltet/.test(pilot),'install/access separation missing');
must(/completion_received/.test(sw),'completion receipt missing in service worker');
must(/echten Köcheclub-Daten/.test(test),'isolated tester notice missing');
must(!/supabase\.co|KC_WERNE|kc_dp_memberships/i.test(test),'isolated tester page must not connect to production backend');
console.log(`KC DP2 V${current.version} installation history gate: PASS`);
