const fs=require('fs'),path=require('path');
const current=require('../release/current.json');
const parts=String(current.version||'').split('.').map(Number);
if(parts.length!==3 || parts.some(Number.isNaN) || parts[0]!==0 || parts[1]!==19 || parts[2]<48) throw new Error('current release predates guided pilot V0.19.48');
const root=path.join(__dirname,'..',current.releasePath);
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('pilot/index.html');
const app=read('src/ui/pilot-app.js');
const core=read('src/core/pilot-onboarding.js');
const sw=read('pilot-sw.js');
const ios=JSON.parse(read('pilot/manifest-ios.webmanifest'));
function must(v,m){if(!v)throw new Error(m)}
must(/manifest-ios\.webmanifest/.test(html),'iOS manifest selector missing');
must(!Object.prototype.hasOwnProperty.call(ios,'start_url'),'iOS manifest must preserve installing document URL');
must(ios.scope==='./','iOS pilot scope must stay isolated');
must(/version:'0\.19\.48'/.test(core),'guided pilot core baseline mismatch');
must(/flowVersion:'0\.19\.51-auto3'/.test(core),'pilot flow version check baseline missing');
must(/markVersionChecked/.test(core),'version-check persistence missing');
must(/data-pilot-device="pc"/.test(html),'PC selector missing');
must(/data-pilot-device="handy"/.test(html),'Handy selector missing');
must(/data-pilot-device="tablet"/.test(html),'Tablet selector missing');
must(/Bei „Handy“ wird Push sofort abgefragt/.test(html),'first-screen push cue missing');
must(/0\.19\.51-auto4/.test(html),'pilot error-recovery cache bump missing');
must(!/pilotInstallBtn|pilotPushBtn|pilotTestBtn/.test(html),'legacy multi-click pilot controls must not return');
must(/TARGET_VERSION='0\.19\.51',PILOT_BUILD='0\.19\.51-auto4'/.test(app),'target install/build version missing');
must(/requestHandyPushPermissionNow/.test(app),'immediate Handy push permission function missing');
must(/phase:'push_permission_first_screen'/.test(app),'first-screen push permission telemetry missing');
must(/if\(b\.dataset\.pilotDevice==='handy'\)await requestHandyPushPermissionNow\(\)/.test(app),'Handy selector must request push before install flow');
must(/Push wurde nicht genehmigt/.test(app),'permission denial must stop clearly');
must(/P\.device\(\)==='ios'&&!standalone\(\)/.test(app),'iOS pre-install permission deferral missing');
must(/systemStep\('Push genehmigen'/.test(app),'installed iOS must surface one-tap push permission');
must(/detectExistingInstallation/.test(app),'pre-install version inventory missing');
must(/navigator\.serviceWorker\.getRegistrations/.test(app),'existing service worker detection missing');
must(/pushManager\.getSubscription/.test(app),'existing push subscription detection missing');
must(/kc-dp-release-meta-v1/.test(app),'active DP2 release cache detection missing');
must(/installDisposition/.test(app),'reuse-update-new decision missing');
must(/disposition==='update'/.test(app),'older-version automatic update path missing');
must(/inv\.reliable/.test(app),'duplicate-install prevention missing');
must(/runAutoFlow\(true\)/.test(app),'one-tap automatic flow missing');
must(/Notification\.requestPermission\(\)/.test(app),'notification permission request missing');
must(/call\('send_test'\)/.test(app),'automatic server test push missing');
must(/KC_DP_PILOT_CONTEXT/.test(app),'pilot receipt context handoff missing');
must(/KC_DP_PILOT_PUSH_RECEIVED/.test(app),'automatic push receipt UI confirmation missing');
must(/Nochmal versuchen/.test(app),'simple retry action missing');
must(/Abbrechen/.test(app),'simple abort action missing');
must(/Meldung senden/.test(app),'simple error report action missing');
must(/call\('report_error'/.test(app),'server error reporting missing');
must(/friendlyError/.test(app),'plain-language error mapping missing');
must(/KC_DP_PILOT_CONTEXT/.test(sw),'service worker pilot context storage missing');
must(/test_received/.test(sw),'service worker automatic test receipt missing');
must(/kc-dp2-pilot-v01951-auto1/.test(sw),'pilot service-worker baseline missing');
must(/Safari: Teilen → Zum Home-Bildschirm → Hinzufügen/.test(app),'minimal iOS install instruction missing');
console.log(`KC DP2 V${current.version} automatic pilot usability/error gate: PASS`);
